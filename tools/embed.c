/* embed - turns files into a C table so the .exe carries its own UI and page scripts.
   usage: embed OUT.c NAME=FILE [NAME=FILE ...]
   Every array gets one extra NUL byte (not counted in the size) so text files can be used as C strings. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int main(int argc, char **argv)
{
    if (argc < 3) { fprintf(stderr, "usage: embed OUT.c NAME=FILE ...\n"); return 64; }
    FILE *out = fopen(argv[1], "wb");
    if (!out) { fprintf(stderr, "embed: cannot write %s\n", argv[1]); return 73; }
    int count = argc - 2;
    unsigned long *sizes = (unsigned long *)calloc((size_t)count, sizeof *sizes);
    if (!sizes) { fclose(out); return 71; }

    fprintf(out, "/* generated by tools/embed.c - do not edit */\n#include <stddef.h>\n");
    fprintf(out, "typedef struct { const char *name; const unsigned char *data; unsigned long size; } FbEmbed;\n");
    for (int i = 0; i < count; i++) {
        char *eq = strchr(argv[i + 2], '=');
        if (!eq) { fprintf(stderr, "embed: expected NAME=FILE, got %s\n", argv[i + 2]); fclose(out); return 64; }
        FILE *in = fopen(eq + 1, "rb");
        if (!in) { fprintf(stderr, "embed: cannot read %s\n", eq + 1); fclose(out); return 66; }
        fprintf(out, "static const unsigned char d%d[] = {", i);
        int c;
        while ((c = fgetc(in)) != EOF) {
            if (sizes[i] % 32 == 0) fputc('\n', out);
            fprintf(out, "%d,", c);
            sizes[i]++;
        }
        fprintf(out, "0};\n");
        fclose(in);
    }
    fprintf(out, "const FbEmbed fb_embedded[] = {\n");
    for (int i = 0; i < count; i++) {
        char *spec = argv[i + 2];
        char *eq = strchr(spec, '=');
        fprintf(out, "  { \"");
        for (char *p = spec; p < eq; p++) fputc(*p == '\\' ? '/' : *p, out);
        fprintf(out, "\", d%d, %luul },\n", i, sizes[i]);
    }
    fprintf(out, "  { 0, 0, 0 }\n};\nconst int fb_embedded_count = %d;\n", count);
    free(sizes);
    if (fclose(out)) { fprintf(stderr, "embed: write error\n"); return 74; }
    return 0;
}
