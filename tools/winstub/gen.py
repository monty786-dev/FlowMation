#!/usr/bin/env python3
"""Generates tests/winstub/gen_decls.h and WebView2.h from the identifiers the Windows sources actually use.
The stubs only let clang parse the Windows layer on Linux (syntax / typo / undeclared-name check). They do not
check argument types or COM vtable layouts - the real build in CI does that."""
import re, sys, os, glob
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
srcs = glob.glob(os.path.join(root, 'src/win/*.c')) + glob.glob(os.path.join(root, 'src/win/*.h')) + [os.path.join(root, 'src/core/fb_util.c')]
text = '\n'.join(open(s, encoding='utf-8').read() for s in srcs)
text_nc = re.sub(r"'(\\.|[^'\\])'", "' '", text)
text_nc = re.sub(r'"(\\.|[^"\\\n])*"', '""', text_nc)
text_nc = re.sub(r'/\*.*?\*/', '', text_nc, flags=re.S)
text_nc = re.sub(r'//[^\n]*', '', text_nc)

# ---- COM interfaces ----
types = sorted(set(re.findall(r'\bICoreWebView2[A-Za-z0-9]*\b', text_nc)))
com_funcs = sorted(set(re.findall(r'\b(?:ICoreWebView2[A-Za-z0-9]*|IUnknown|IStream)_[A-Za-z0-9_]+\b', text_nc)))
for ev in set(re.findall(r'ADD_EVENT\([^,]+,\s*(\w+),', text_nc)):
    com_funcs.append('ICoreWebView2_add_' + ev)
    types.append('ICoreWebView2%sEventHandler' % ev)
com_funcs = sorted(set(com_funcs)); types = sorted(set(types))
types = [t for t in types if '_' not in t]
enum_types = ['COREWEBVIEW2_WEB_ERROR_STATUS', 'COREWEBVIEW2_SCRIPT_DIALOG_KIND', 'COREWEBVIEW2_KEY_EVENT_KIND', 'COREWEBVIEW2_PERMISSION_STATE',
              'COREWEBVIEW2_MOVE_FOCUS_REASON', 'COREWEBVIEW2_WEB_RESOURCE_CONTEXT']
consts = sorted(set(re.findall(r'\bCOREWEBVIEW2_[A-Z0-9_]+\b', text_nc)) - set(enum_types))
out = ['/* generated by gen.py - WebView2 stub for syntax checking only */', '#pragma once', '#include "windows.h"']
for t in types: out.append('typedef struct %s %s;' % (t, t))
for e in enum_types: out.append('typedef int %s;' % e)
for i, c in enumerate(consts): out.append('enum { %s = %d };' % (c, i + 1))
out.append('typedef struct { long long value; } EventRegistrationToken;')
out.append('long CreateCoreWebView2EnvironmentWithOptions();')
for f in com_funcs: out.append('long %s();' % f)
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'WebView2.h'), 'w').write('\n'.join(out) + '\n')

# ---- Win32 names ----
known_types = set(re.findall(r'^\s*typedef[^;]*?\b(\w+)\s*;', open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'windows.h')).read(), re.M))
ptr_ret = {
 'CreateWindowExW': 'HWND', 'GetModuleHandleW': 'HMODULE', 'GetProcAddress': 'void *', 'LoadIconW': 'HICON', 'LoadCursorW': 'HCURSOR',
 'CreateEventW': 'HANDLE', 'CreateThread': 'HANDLE', 'CreateFileW': 'HANDLE', 'GlobalAlloc': 'HGLOBAL', 'GlobalLock': 'void *', 'GetDC': 'HDC',
 'CommandLineToArgvW': 'wchar_t **', 'GetCommandLineW': 'wchar_t *', 'SHCreateMemStream': 'IStream *', 'CreateSolidBrush': 'HBRUSH',
 'MonitorFromWindow': 'HMONITOR', 'GetStdHandle': 'HANDLE', 'SetClipboardData': 'HANDLE', 'LocalFree': 'void *', 'FindFirstFileW': 'HANDLE',
 'FindFirstFileExW': 'HANDLE', '_wfopen': 'void *', '_wcsdup': 'wchar_t *', 'ShellExecuteW': 'HINSTANCE', 'GetClipboardData': 'HANDLE',
 'GetCurrentProcess': 'HANDLE', 'OpenProcess': 'HANDLE', 'CoTaskMemAlloc': 'void *', '_wgetenv': 'wchar_t *', 'GetEnvironmentStringsW': 'wchar_t *',
}
funcs = sorted(set(re.findall(r'\b([A-Z_][A-Za-z0-9]+)\s*\(', text_nc)))
skip = set()
for line in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'windows.h')):
    if line.lstrip().startswith('typedef'):
        skip.update(re.findall(r'[A-Za-z_]\w*', line))

for f in re.findall(r'^(?:static\s+)?[A-Za-z_][\w \*]*?\b(\w+)\s*\([^;{]*\)\s*(?:\{|;)', text_nc, re.M): skip.add(f)
for m in re.findall(r'#define\s+(\w+)', text_nc): skip.add(m)
win = []
for f in funcs:
    if f in skip or f.startswith('fb') or f.startswith('FB') or f.startswith('ICoreWebView2') or f.startswith('COREWEBVIEW2'): continue
    win.append(f)
lines = ['/* generated by gen.py */']
for f in win:
    if f in ('MAKEINTRESOURCEW', 'LOWORD', 'HIWORD', 'FAILED', 'SUCCEEDED', 'IsEqualIID', '_wcsdup', '_strnicmp', 'RGB') or f.startswith('Interlocked'): continue
    lines.append('%s %s();' % (ptr_ret.get(f, 'long'), f))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gen_decls.h'), 'w').write('\n'.join(lines) + '\n')
print('com funcs', len(com_funcs), 'types', len(types), 'consts', len(consts), 'win funcs', len(win))
